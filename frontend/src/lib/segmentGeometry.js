/**
 * 折線的中點 [lng, lat] — 以累積線長取一半，不是取中間那個節點。
 * 節點分佈不均的路段（例如只有兩端點的短段）用節點取法會偏到一邊。
 */
function midpointOfLine(coords) {
  if (!Array.isArray(coords) || coords.length === 0) return null;
  if (coords.length === 1) return coords[0];

  const segLens = [];
  let totalLen = 0;
  for (let i = 1; i < coords.length; i++) {
    const dx = coords[i][0] - coords[i - 1][0];
    const dy = coords[i][1] - coords[i - 1][1];
    const len = Math.sqrt(dx * dx + dy * dy);
    segLens.push(len);
    totalLen += len;
  }
  if (totalLen === 0) return coords[0];

  const target = totalLen / 2;
  let accumulated = 0;
  for (let i = 0; i < segLens.length; i++) {
    if (accumulated + segLens[i] >= target) {
      const ratio = segLens[i] === 0 ? 0 : (target - accumulated) / segLens[i];
      return [
        coords[i][0] + ratio * (coords[i + 1][0] - coords[i][0]),
        coords[i][1] + ratio * (coords[i + 1][1] - coords[i][1]),
      ];
    }
    accumulated += segLens[i];
  }
  return coords[coords.length - 1];
}

/**
 * 事故標記位置 [lng, lat]
 * - 路段（RD_*）：取該路段折線中點，標記落在路上而非端點路口
 * - 人流站點（BS_*）：直接取站點座標
 * - 查不到：退回信義計畫區中心，地圖仍可正常呈現
 */
export function incidentPointFor(segmentId) {
  const line = SEGMENT_COORDS[segmentId];
  if (line) return midpointOfLine(line) ?? XINYI_CENTER;
  const station = STATION_COORDS[segmentId];
  if (station) return station;
  return XINYI_CENTER;
}
